"""Builds firmware/src/web_page.h from firmware/web/index.html (ADR-0016).

The page is gzipped (fixed mtime, so the output only changes with the page)
and embedded as a byte array; the server sends it with Content-Encoding: gzip.

    python3 tools/gen_web.py          # from firmware/
    python3 tools/gen_web.py --check  # exit 1 if web_page.h is out of date (CI)
"""
import gzip
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "web" / "index.html"
OUT = ROOT / "src" / "web_page.h"


def render() -> str:
    data = gzip.compress(SRC.read_bytes(), compresslevel=9, mtime=0)
    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    return (
        "// SPDX-License-Identifier: GPL-3.0-only\n"
        "// Generated by tools/gen_web.py from web/index.html: do not edit.\n"
        "#pragma once\n\n"
        "#include <cstddef>\n#include <cstdint>\n\n"
        "// clang-format off\n"
        "namespace inkwake::web {\n\n"
        f"constexpr size_t kIndexGzLen = {len(data)};\n"
        "constexpr uint8_t kIndexGz[kIndexGzLen] = {\n"
        + "\n".join(rows)
        + "\n};\n\n}  // namespace inkwake::web\n// clang-format on\n"
    )


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python3 tools/gen_web.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
