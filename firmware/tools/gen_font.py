"""Render a TrueType font into a 1-bit C++ header for lib/display (font.h).

Needs Pillow (pip install pillow). Example, from firmware/:

  python3 tools/gen_font.py /usr/share/fonts/truetype/lato/Lato-Bold.ttf 200 \
      --chars "0123456789:" --name kClockDigits --out lib/display/src/fonts/clock_digits.h

--chars defaults to printable ASCII plus the degree sign. Glyphs are stored for
the whole codepoint range first..last; codepoints not in --chars are blank.
"""

import argparse
import os

from PIL import Image, ImageDraw, ImageFont

DEFAULT_CHARS = "".join(chr(c) for c in range(0x20, 0x7F)) + "°"


def render(font, ch):
    """Return (width, height, left, top, advance, bits) for one character."""
    advance = round(font.getlength(ch))
    l, t, r, b = font.getbbox(ch, anchor="ls")
    if r <= l or b <= t:
        return 0, 0, 0, 0, advance, []
    img = Image.new("L", (r - l, b - t), 0)
    ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
    img = img.point(lambda v: 255 if v >= 128 else 0)
    box = img.getbbox()
    if box is None:
        return 0, 0, 0, 0, advance, []
    img = img.crop(box)
    w, h = img.size
    px = img.load()
    bits = [1 if px[x, y] else 0 for y in range(h) for x in range(w)]
    return w, h, l + box[0], t + box[1], advance, bits


def pack(bits):
    out = bytearray((len(bits) + 7) // 8)
    for i, bit in enumerate(bits):
        if bit:
            out[i >> 3] |= 0x80 >> (i & 7)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("ttf")
    ap.add_argument("size", type=int, help="pixel size passed to FreeType")
    ap.add_argument("--chars", default=DEFAULT_CHARS)
    ap.add_argument("--name", required=True, help="C++ name of the Font, e.g. kClockDigits")
    ap.add_argument("--out", required=True)
    ap.add_argument("--licence", default="OFL-1.1", help="licence of the source font")
    args = ap.parse_args()

    font = ImageFont.truetype(args.ttf, args.size)
    chars = sorted(set(args.chars))
    first, last = ord(chars[0]), ord(chars[-1])

    bitmap = bytearray()
    glyphs = []
    for cp in range(first, last + 1):
        ch = chr(cp)
        if ch not in chars:
            glyphs.append((0, 0, 0, 0, 0, 0))
            continue
        w, h, left, top, adv, bits = render(font, ch)
        glyphs.append((len(bitmap), w, h, left, top, adv))
        bitmap += pack(bits)

    # Cap height for layout: digits if present, else 'H'.
    ref = "0" if "0" in chars else "H" if "H" in chars else chars[0]
    ascent = -render(font, ref)[3]
    asc, desc = font.getmetrics()
    line_height = asc + desc

    base = args.name[1:] if args.name.startswith("k") else args.name
    src = os.path.basename(args.ttf)
    lines = [
        "// SPDX-License-Identifier: " + args.licence,
        f"// Generated by tools/gen_font.py from {src} at {args.size} px. Do not edit.",
        f"// Bitmap rendering of {src}, licence {args.licence} (see fonts/LICENSE-fonts.md).",
        "// clang-format off",
        "#pragma once",
        "",
        '#include "../font.h"',
        "",
        "namespace inkwake::fonts {",
        "",
        f"inline constexpr uint8_t k{base}Bitmap[] = {{",
    ]
    for i in range(0, len(bitmap), 16):
        lines.append("    " + " ".join(f"0x{b:02X}," for b in bitmap[i : i + 16]))
    if not bitmap:
        lines.append("    0x00,")
    lines.append("};")
    lines.append("")
    lines.append(f"inline constexpr Glyph k{base}Glyphs[] = {{")
    for cp, (off, w, h, left, top, adv) in zip(range(first, last + 1), glyphs):
        label = chr(cp) if 0x20 < cp < 0x7F and chr(cp) not in "\\" else f"U+{cp:04X}"
        lines.append(f"    {{{off}, {w}, {h}, {left}, {top}, {adv}}},  // {label}")
    lines.append("};")
    lines.append("")
    lines.append(
        f"inline constexpr Font {args.name} = {{k{base}Bitmap, k{base}Glyphs, {first}, {last}, "
        f"{ascent}, {line_height}}};"
    )
    lines.append("")
    lines.append("}  // namespace inkwake::fonts")
    lines.append("")
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"{args.out}: {len(bitmap)} bitmap bytes, {len(glyphs)} glyphs, ascent {ascent}")


if __name__ == "__main__":
    main()
